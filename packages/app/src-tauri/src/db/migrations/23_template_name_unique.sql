-- ============================================================================
-- IcePaw Migration 23: 模板名称 UNIQUE 约束
-- ----------------------------------------------------------------------------
-- 背景：REQ-TMPL-001a 要求 templates.name 在数据库层面保持唯一，
--       防止两个模板重名导致聊天 @ 触发时匹配歧义。
--
-- 设计：
--   - 在 templates.name 上建立 UNIQUE INDEX（而非改列约束），可避免
--     重建表、对现有数据更友好。
--   - 索引命名遵循既有约定 `idx_<table>_<column>`。
--   - 唯一性预检（应用层）+ UNIQUE 约束（DB 层）双保险：
--       * 应用层预检给出结构化 Duplicate 错误（kind=duplicate）
--       * DB 层在并发场景下兜底（两个请求同时通过预检时）
--
-- 兼容性：
--   - CREATE UNIQUE INDEX IF NOT EXISTS 幂等；如已存在同名索引则跳过
--   - 假设 02_templates.sql 历史数据中 name 本身已唯一（前端此前未限制），
--     但若已有重名数据，迁移会失败；上线前需手动清理。
-- ============================================================================

CREATE UNIQUE INDEX IF NOT EXISTS idx_templates_name ON templates(name);
