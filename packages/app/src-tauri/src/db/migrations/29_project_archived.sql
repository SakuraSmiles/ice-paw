-- ============================================================================
-- IcePaw Migration 29: 项目归档（软删除）
-- ----------------------------------------------------------------------------
-- 背景：删除项目时其会话的去向（转散落 / 一并删除）都不理想——转散落丢语境、
--       删除丢历史。改为「归档」：项目可逆地收起，会话不动、不丢、不混入散落。
--
-- 设计：
--   - 新增 archived INTEGER NOT NULL DEFAULT 0（0 = 活跃，1 = 已归档）
--   - 归档项目从切换器 / 管理页活跃列表消失，但其会话仍归属该项目（project_id 不变），
--     因此既不进散落、也不进任何活跃项目 scope，整体隐藏；恢复（unarchive）即原样回来。
--
-- 兼容性：
--   - ALTER TABLE ADD COLUMN 引入新列（DEFAULT 0），老项目自动视为活跃。
--   - sqlx::migrate! 按文件名执行，不重复。
-- ============================================================================

ALTER TABLE projects ADD COLUMN archived INTEGER NOT NULL DEFAULT 0;
